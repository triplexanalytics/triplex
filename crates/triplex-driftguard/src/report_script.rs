//! `reproduce.py`: the reproducible local Python/Polars script of the
//! CI/CD output contract -- lets
//! a reviewer independently re-check the numeric drift thresholds (null
//! rate, mean) with no Rust toolchain and no trust in this binary's output.
//!
//! ponytail: only re-derives the numeric checks (null rate, mean), not
//! column add/remove or type-consistency -- those need this crate's own
//! type-inference/consistency-scoring logic (`triplex-schemacast`), and
//! reimplementing that in Python is a separate, much larger undertaking for
//! comparatively little independent-verification value. Upgrade if a
//! reviewer specifically needs to audit a type or consistency finding
//! without trusting the Rust engine.

use crate::DriftThresholds;

fn python_reader(path: &str) -> &'static str {
    if path.ends_with(".parquet") {
        "pl.read_parquet"
    } else if path.ends_with(".tsv") {
        "lambda p: pl.read_csv(p, separator='\\t')"
    } else if path.ends_with(".jsonl") {
        "pl.read_ndjson"
    } else {
        "pl.read_csv"
    }
}

/// Renders a standalone Python script (Polars only, no other dependency)
/// that recomputes the null-rate and mean checks `compare_paths` runs in
/// Rust, using the same file paths and thresholds, and exits non-zero if it
/// finds the same drift.
pub fn render_python_script(
    baseline_path: &str,
    candidate_path: &str,
    thresholds: &DriftThresholds,
) -> String {
    format!(
        r#"#!/usr/bin/env python3
"""Reproduces DriftGuard's null-rate/mean drift check with Polars only.

Generated by `triplex driftguard` -- see report.html/audit.json for the full
finding set, including schema regressions and type-consistency drift this
script does not re-derive (see this file's module doc for why).
"""

import sys

import polars as pl

BASELINE_PATH = {baseline_path:?}
CANDIDATE_PATH = {candidate_path:?}
MAX_NULL_PERCENTAGE_DELTA = {max_null_percentage_delta}
MAX_MEAN_RELATIVE_DELTA = {max_mean_relative_delta}


def null_percentage(df, column):
    return df[column].null_count() / len(df) * 100.0 if len(df) else 0.0


def main():
    baseline = {baseline_reader}(BASELINE_PATH)
    candidate = {candidate_reader}(CANDIDATE_PATH)

    drifted = False
    shared_columns = [c for c in baseline.columns if c in candidate.columns]

    for column in shared_columns:
        base_null = null_percentage(baseline, column)
        cand_null = null_percentage(candidate, column)
        null_delta = abs(cand_null - base_null)
        if null_delta > MAX_NULL_PERCENTAGE_DELTA:
            drifted = True
            print(
                f"NullRateDrift: {{column}} {{base_null:.2f}}% -> {{cand_null:.2f}}% "
                f"(delta {{null_delta:.2f}}pp, threshold {{MAX_NULL_PERCENTAGE_DELTA:.2f}}pp)"
            )

        if not baseline[column].dtype.is_numeric() or not candidate[column].dtype.is_numeric():
            continue
        base_mean = baseline[column].mean()
        cand_mean = candidate[column].mean()
        if base_mean is None or cand_mean is None or base_mean == 0:
            continue
        relative_delta = abs((cand_mean - base_mean) / base_mean)
        if relative_delta > MAX_MEAN_RELATIVE_DELTA:
            drifted = True
            print(
                f"MeanDrift: {{column}} {{base_mean:.4f}} -> {{cand_mean:.4f}} "
                f"(relative delta {{relative_delta:.2f}}, threshold {{MAX_MEAN_RELATIVE_DELTA:.2f}})"
            )

    if not drifted:
        print("No null-rate/mean drift detected.")
    sys.exit(1 if drifted else 0)


if __name__ == "__main__":
    main()
"#,
        baseline_path = baseline_path,
        candidate_path = candidate_path,
        max_null_percentage_delta = thresholds.max_null_percentage_delta,
        max_mean_relative_delta = thresholds.max_mean_relative_delta,
        baseline_reader = python_reader(baseline_path),
        candidate_reader = python_reader(candidate_path),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embeds_paths_and_thresholds_as_python_literals() {
        let script = render_python_script(
            "baseline.csv",
            "candidate.parquet",
            &DriftThresholds::default(),
        );
        assert!(script.contains("BASELINE_PATH = \"baseline.csv\""));
        assert!(script.contains("CANDIDATE_PATH = \"candidate.parquet\""));
        assert!(script.contains("pl.read_parquet"));
        assert!(script.contains("MAX_NULL_PERCENTAGE_DELTA = 5"));
    }
}
